/**
 * Tool wire types shared by every provider: what a tool looks like
 * (`ToolDefinition`), what a model's call to it looks like (`ToolCall`), and
 * whether the caller lets the model skip calling one (`ToolChoice`).
 *
 * `ToolDefinition` and `ToolCall` moved here verbatim from `types.ts`
 * (2026-11-06, tool_choice work); `types.ts` re-exports them so existing
 * importers are unaffected.
 */
import { Schema } from "effect";

// ─── Tool Definition ───

/**
 * Schema for tool definitions.
 * Describes tools available to the LLM, including name, description, and input schema.
 * Tools are passed to the LLM for function calling / tool use.
 *
 * @example
 * ```typescript
 * const tool: ToolDefinition = {
 *   name: "file-read",
 *   description: "Read a file from disk",
 *   inputSchema: {
 *     path: { type: "string", description: "File path", required: true }
 *   }
 * };
 * ```
 */
export const ToolDefinitionSchema = Schema.Struct({
  /** Tool identifier (used by model to invoke the tool) */
  name: Schema.String,
  /** Human-readable tool description for the model */
  description: Schema.String,
  /** Input schema describing expected parameters (JSON Schema format) */
  inputSchema: Schema.Record({ key: Schema.String, value: Schema.Unknown }),
});

/**
 * Tool definition.
 * Used to register available functions that the LLM can call.
 * Input schema is a JSON Schema object defining parameters.
 */
export type ToolDefinition = Schema.Schema.Type<typeof ToolDefinitionSchema>;

// ─── Tool Call ───

/**
 * Schema for tool invocation.
 * Emitted by the model when it decides to call a tool.
 *
 * @example
 * ```typescript
 * const call: ToolCall = {
 *   id: "toolu_123",
 *   name: "file-read",
 *   input: { path: "./output.txt" }
 * };
 * ```
 */
export const ToolCallSchema = Schema.Struct({
  /** Unique tool call identifier (generated by model) */
  id: Schema.String,
  /** Tool name to invoke */
  name: Schema.String,
  /** Tool input parameters (arbitrary JSON-compatible object) */
  input: Schema.Unknown,
});

/**
 * Tool invocation from the LLM.
 * When the model decides to call a tool, this describes which tool and with what inputs.
 */
export type ToolCall = Schema.Schema.Type<typeof ToolCallSchema>;

// ─── Tool Choice ───

/**
 * Whether the model may answer without calling a tool.
 *
 * - `"auto"`: the model decides (the provider default; same as omitting it).
 * - `"required"`: the response must carry at least one call to a tool in
 *   `CompletionRequest.tools`. Ignored when `tools` is empty or absent.
 *
 * How each provider honors `"required"`, on both `complete()` and `stream()`:
 * - Anthropic: `tool_choice: { type: "any" }`. Anthropic rejects a forced
 *   tool choice together with extended thinking, so thinking is turned off
 *   for that call.
 * - OpenAI and OpenAI-compatible (Groq, xAI, ...), LiteLLM:
 *   `tool_choice: "required"`.
 * - Gemini: `toolConfig.functionCallingConfig.mode = "ANY"`.
 * - Ollama: constrained decoding. The `tools` param is not sent; `format` is
 *   a JSON schema that only admits `{ tool, arguments }` for one of the
 *   offered tools, and the JSON is read back as a normal tool call. Thinking
 *   defaults off for that call, as for `completeStructured`. `stream()` runs
 *   the call non-streamed and emits the result as stream events. Output that
 *   does not parse comes back as a plain text response, never an error.
 *   The model sees tool names and argument schemas through the grammar only,
 *   not tool descriptions, so the prompt should name the tools.
 * - Test provider: accepted, no behavior change.
 */
export type ToolChoice = "auto" | "required";

/**
 * True when the request forces a tool call: `toolChoice` is `"required"` and
 * at least one tool is offered. Every adapter gates its mapping on this, so an
 * omitted or `"auto"` choice leaves the request untouched.
 */
export const isToolCallRequired = (request: {
  readonly toolChoice?: ToolChoice;
  readonly tools?: readonly ToolDefinition[];
}): boolean =>
  request.toolChoice === "required" && (request.tools?.length ?? 0) > 0;
