// A caller-supplied plan (core or strategy shape) replaces the planner LLM call
// in blueprint and plan-execute. The plan is validated first: a bad dependency
// graph or an empty plan is a typed ExecutionError, never a half-run.
import { Effect } from "effect";
import type { LLMService } from "@reactive-agents/llm-provider";
import { findPlanDependencyProblem } from "@reactive-agents/core";
import type { Plan as CorePlan } from "@reactive-agents/core";
import { ExecutionError } from "../../errors/errors.js";
import { LLMPlanOutputSchema, hydratePlan } from "../../types/plan.js";
import type { Plan, PlanContext } from "../../types/plan.js";
import { fromCorePlan, isCorePlan, toCorePlan } from "../../types/plan-adapters.js";
import { resolveProfile } from "../../context/profile-resolver.js";
import { extractStructuredOutput, structuredCallSpend } from "../../structured-output/pipeline.js";
import { buildPlanGenerationPrompt } from "./plan-prompts.js";
import type { ToolSummary } from "./plan-prompts.js";
import type { StrategyRun } from "../substrate/strategy-run.js";

/** A plan a caller hands to a strategy: portable core shape or strategy shape. */
export type InputPlan = CorePlan | Plan;

/**
 * Validate and adopt a caller-supplied plan as the strategy's working plan.
 * Fails with `ExecutionError` (step 0) when the plan is empty or its
 * `dependsOn` graph has an unknown id, self reference or cycle.
 */
export const adoptInputPlan = (
  input: InputPlan,
  ctx: PlanContext,
  strategy: string,
): Effect.Effect<Plan, ExecutionError> => {
  const core = isCorePlan(input) ? input : toCorePlan(input);
  const problem =
    core.steps.length === 0 ? "Input plan has no steps." : findPlanDependencyProblem(core);
  if (problem !== undefined) {
    return Effect.fail(new ExecutionError({ strategy, message: `Invalid input plan: ${problem}`, step: 0 }));
  }
  return Effect.succeed(isCorePlan(input) ? fromCorePlan(input, ctx) : input);
};

/** What `obtainPlan` needs beyond the strategy input. */
export interface ObtainPlanParams {
  readonly input: {
    readonly plan?: InputPlan;
    readonly systemPrompt?: string;
    readonly taskId?: string;
    readonly temperature?: number;
    readonly modelId?: string;
    readonly requiredToolQuantities?: Readonly<Record<string, number>>;
  };
  readonly goal: string;
  readonly taskId: string;
  readonly agentId: string;
  readonly planMode: "linear" | "dag";
  readonly strategy: "blueprint" | "plan-execute-reflect";
  readonly persona: string;
  readonly defaultTemperature: number;
  readonly pastPatterns: readonly string[];
  readonly toolSummaries: readonly ToolSummary[];
  readonly run: Pick<StrategyRun, "account">;
}

/**
 * The strategy's initial plan: the caller-supplied `input.plan` (validated, no
 * planner call) or one generated by the planner LLM. `planPrompt` is empty for
 * a supplied plan (nothing to retry).
 */
export const obtainPlan = (
  p: ObtainPlanParams,
): Effect.Effect<{ readonly plan: Plan; readonly planPrompt: string }, ExecutionError, LLMService> => {
  const ctx: PlanContext = { taskId: p.taskId, agentId: p.agentId, goal: p.goal, planMode: p.planMode };
  if (p.input.plan !== undefined) {
    return adoptInputPlan(p.input.plan, ctx, p.strategy).pipe(Effect.map((plan) => ({ plan, planPrompt: "" })));
  }
  return Effect.gen(function* () {
    const planPrompt = buildPlanGenerationPrompt({
      goal: p.goal,
      tools: [...p.toolSummaries],
      pastPatterns: [...p.pastPatterns],
      modelTier: resolveProfile(p.input.modelId ?? "mid").tier,
      requiredToolQuantities: p.input.requiredToolQuantities,
    });
    const planResult = yield* extractStructuredOutput({
      schema: LLMPlanOutputSchema,
      prompt: planPrompt,
      systemPrompt: p.input.systemPrompt ? `${p.input.systemPrompt}\n${p.persona}` : p.persona,
      strategy: p.strategy,
      maxRetries: 2,
      // GH #246: commanded temperature wins.
      temperature: p.input.temperature ?? p.defaultTemperature,
      maxTokens: 4096,
      ...(p.input.taskId ? { traceContext: { taskId: p.input.taskId } } : {}),
    }).pipe(
      Effect.mapError(
        (err) => new ExecutionError({ strategy: p.strategy, message: `Plan generation failed: ${err.message}`, step: 0, cause: err }),
      ),
    );
    // Provider-reported planner usage; estimate only when none reported.
    p.run.account(structuredCallSpend(planResult.usage, { prompt: planPrompt, raw: planResult.raw }));
    return { plan: hydratePlan(planResult.data, ctx), planPrompt };
  });
};
