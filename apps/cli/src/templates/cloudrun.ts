// apps/cli/src/templates/cloudrun.ts

/** Auth + always-on settings shared by the cloudbuild template and the deploy command. */
export interface CloudRunSettings {
  /** Public, unauthenticated access. Default false: callers need an IAM identity token. */
  readonly allowUnauthenticated?: boolean;
  /** Daemon mode: keep one instance warm with CPU always allocated (cron/heartbeat need it). */
  readonly daemon?: boolean;
}

/** gcloud flags for auth + always-on behaviour (argv elements, never shell-parsed). */
export const cloudRunFlags = (s: CloudRunSettings = {}): string[] => [
  s.allowUnauthenticated ? "--allow-unauthenticated" : "--no-allow-unauthenticated",
  ...(s.daemon ? ["--min-instances=1", "--no-cpu-throttling"] : []),
];

/** Generate a cloudbuild.yaml for Google Cloud Run */
export const cloudRunYamlTemplate = (
  agentName: string,
  projectId: string = "YOUR_PROJECT_ID",
  region: string = "us-central1",
  settings: CloudRunSettings = {},
) => `# Google Cloud Build + Cloud Run — raxd agent
# Generated by: rax deploy up --target cloudrun
# Docs: https://cloud.google.com/run/docs
#
# Deploy manually:
#   gcloud run deploy raxd-${agentName} \\
#     --source . \\
#     --region ${region} \\
${cloudRunFlags(settings).map((f) => `#     ${f} \\\n`).join("")}#     --set-env-vars PORT=3000

steps:
  - name: "gcr.io/cloud-builders/docker"
    args:
      - "build"
      - "-t"
      - "gcr.io/${projectId}/raxd-${agentName}"
      - "."

  - name: "gcr.io/cloud-builders/docker"
    args:
      - "push"
      - "gcr.io/${projectId}/raxd-${agentName}"

  - name: "gcr.io/google.com/cloudsdktool/cloud-sdk"
    entrypoint: gcloud
    args:
      - "run"
      - "deploy"
      - "raxd-${agentName}"
      - "--image"
      - "gcr.io/${projectId}/raxd-${agentName}"
      - "--region"
      - "${region}"
      - "--platform"
      - "managed"
      - "--port"
      - "3000"
      - "--memory"
      - "512Mi"
      - "--timeout"
      - "300"
${cloudRunFlags(settings).map((f) => `      - "${f}"\n`).join("")}
images:
  - "gcr.io/${projectId}/raxd-${agentName}"
`;

